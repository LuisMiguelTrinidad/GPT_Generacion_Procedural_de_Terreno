float vec2_dot(Vector2 a, Vector2 b) {
    return (a.x * b.x + a.y * b.y);
}

float bilinear_interp(float bl, float br, float tl, float tr, Vector2 t) {
    float bottom = (1.0f - t.x) * bl + t.x * br;
    float top = (1.0f - t.x) * tl + t.x * tr;
    return (1.0f - t.y) * bottom + t.y * top;
}

uint8_t hash(uint64_t seed, int64_t x, int64_t y) {
    const uint64_t C1 = 0xbf58476d1ce4e5b9ULL; // Wyhash64
    const uint64_t C3 = 0xc4ceb9fe1a85ec53ULL; // MurMurHash3 finalizer

    seed ^= (uint64_t)(x * (int64_t)C1) ^ (uint64_t)(y * (int64_t)C3);

    unsigned long long hi;
    seed = hi ^ _mulx_u64(ROTATE_RIGHT(seed, 32), seed, &hi);
    seed ^= seed >> 32;
    seed = hi ^ _mulx_u64(ROTATE_RIGHT(seed, 32), seed, &hi);
    seed ^= seed >> 16;
    return (uint8_t)seed & 0xFF;
}

Vector2 smoothstep_vec2(Vector2 t) {
    return (Vector2){
        t.x * t.x * t.x * (t.x * (t.x * 6.0f - 15.0f) + 10.0f),
        t.y * t.y * t.y * (t.y * (t.y * 6.0f - 15.0f) + 10.0f)
    };
}

float smoothstep_scalar(float t) {
    return t * t * t * (t * (t * 6.0f - 15.0f) + 10.0f);
}

float fast_fract(float v) {
    return v - floorf(v);
}

uint64_t fast_mod_pow2(uint64_t v, uint64_t scale_mask) {
    return v & scale_mask;
}

int save_grayscale_png(const char *filename, float *image_data, int chunksize) {
    FILE *fp = fopen(filename, "wb");
    if (!fp) {
        fprintf(stderr, "Error: Could not open file %s for writing\n", filename);
        return 1;
    }
    
    png_structp png_ptr = png_create_write_struct(PNG_LIBPNG_VER_STRING, NULL, NULL, NULL);
    if (!png_ptr) {
        fprintf(stderr, "Error: Could not create PNG write struct\n");
        fclose(fp);
        return 1;
    }

    png_infop info_ptr = png_create_info_struct(png_ptr);
    if (!info_ptr) {
        fprintf(stderr, "Error: Could not create PNG info struct\n");
        png_destroy_write_struct(&png_ptr, NULL);
        fclose(fp);
        return 1;
    }

    if (setjmp(png_jmpbuf(png_ptr))) {
        fprintf(stderr, "Error during PNG creation\n");
        png_destroy_write_struct(&png_ptr, &info_ptr);
        fclose(fp);
        return 1;
    }

    png_init_io(png_ptr, fp);

    // Set PNG header information
    png_set_IHDR(png_ptr, info_ptr, chunksize, chunksize,
        8,
        PNG_COLOR_TYPE_GRAY,
        PNG_INTERLACE_NONE,
        PNG_COMPRESSION_TYPE_DEFAULT,
        PNG_FILTER_TYPE_DEFAULT
    );

    png_write_info(png_ptr, info_ptr);

    unsigned char *byte_data = (unsigned char*)malloc(chunksize * chunksize * sizeof(unsigned char));
    png_bytep *row_pointers = (png_bytep*)malloc(chunksize * sizeof(png_bytep));
    
    if (!byte_data || !row_pointers) {
        fprintf(stderr, "Error: Could not allocate memory\n");
        if (byte_data) free(byte_data);
        if (row_pointers) free(row_pointers);
        png_destroy_write_struct(&png_ptr, &info_ptr);
        fclose(fp);
        return 1;
    }

    for (int y = 0; y < chunksize; y++) {
        row_pointers[y] = &byte_data[y * chunksize];
        
        for (int x = 0; x < chunksize; x++) {
            float noise_value = image_data[y * chunksize + x];
            
            float normalized_value = (noise_value + 1.0f) * 0.5f;
            
            if (normalized_value < 0.0f) normalized_value = 0.0f;
            if (normalized_value > 1.0f) normalized_value = 1.0f;
            
            // Convert to 8-bit grayscale [0, 255]
            byte_data[y * chunksize + x] = (unsigned char)(normalized_value * 255.0f);
        }
    }

    // Write image data
    png_write_image(png_ptr, row_pointers);

    // End write
    png_write_end(png_ptr, NULL);

    // Clean up
    free(byte_data);
    free(row_pointers);
    png_destroy_write_struct(&png_ptr, &info_ptr);
    fclose(fp);
    return 0;
}
