from matplotlib import pyplot as plt
import matplotlib.patches as mpatches
import numpy as np
from scipy.stats import chi2, chisquare

import re

def create_uniformity_plot(data_string: str, expected_occurrences: int = 100_000_000):
    pattern = re.compile(r'(\d{3}): (\d{9})')
    matches = pattern.findall(data_string)

    keys = [0.5 + int(key) for key, _ in matches]
    observed_values = [int(value) for _, value in matches]
    percentage_deviations = [(value - expected_occurrences) / expected_occurrences * 100 
        for value in observed_values]

    fig, ax = plt.subplots(figsize=(16, 8))

    fig.suptitle('Análisis de Uniformidad de nuestra función Hash', fontsize=24, fontweight='bold')
    ax.set_title('Desviación porcentual de cada valor (respecto a 100M)', fontsize=20, pad=20)

    ax.set_xlabel('Valores de salida (0-255)', fontsize=16)
    ax.set_ylabel('Desviación Porcentual (%)', fontsize=16)

    bar_colors = ['#33FF57' if d > 0 else '#FF5733' for d in percentage_deviations]
    ax.bar(keys, percentage_deviations, color=bar_colors, alpha=1, width=1, zorder=2)

    ax.axhline(y=0, color='darkgrey', linestyle='-', linewidth=1.5)
    ax.set_ylim(-0.05, 0.05)
    ax.set_xlim(0, 255)

    ax.set_xticks(range(0, 257, 15))
    yticks = np.arange(-0.05, 0.06, 0.01)
    ax.set_yticks(yticks, [f'{y:.2f}%' for y in yticks])

    ax.grid(which='major', axis='both', linestyle='-', color='darkgray', linewidth=1.5, zorder=0)
    ax.grid(which='minor', axis='both', linestyle='--', color='lightgray', linewidth=1, zorder=0)
    ax.minorticks_on()
    ax.xaxis.set_minor_locator(plt.MultipleLocator(5))
    ax.yaxis.set_minor_locator(plt.MultipleLocator(0.005))

    positive_patch = mpatches.Patch(color='#33FF57', label='Desviación Positiva')
    negative_patch = mpatches.Patch(color='#FF5733', label='Desviación Negativa')
    ax.legend(handles=[positive_patch, negative_patch], loc=1, fontsize=12)

    plt.tight_layout()
    plt.savefig('./results/uniformity_analysis.png', dpi=300)
    print("Gráfico de análisis de uniformidad guardado en './results/uniformity_analysis.png'")

    # Análisis de Chi-cuadrado
    degrees_of_freedom = len(observed_values) - 1
    chi2_stat, p_value = chisquare(f_obs=observed_values, f_exp=expected_occurrences)

    alpha = 0.01
    critical_value = chi2.ppf(1 - alpha, degrees_of_freedom)

    print("\nAnálisis de Chi-cuadrado:")
    print(f"  Estadístico Chi-cuadrado: {chi2_stat:.4f}")
    print(f"  Valor p: {p_value:.4f}")
    print(f"  Valor crítico de la tabla (alpha={alpha}, df={degrees_of_freedom}): {critical_value:.4f}")

    if p_value < alpha:
        print("  Resultado: La distribución no es uniforme (se rechaza la hipótesis nula).")
    else:
        print("  Resultado: La distribución es uniforme (no se puede rechazar la hipótesis nula).")

